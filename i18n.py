def init_language_selector() -> str:
    current_language = st.session_state.get("selected_language", "English")
    language = st.selectbox(
        TRANSLATIONS.get(current_language, TRANSLATIONS["English"])[
            "select_language"
        ],
        LANGUAGES,
        key="selected_language",
        bind="query-params",
        format_func=lambda option: {
            "English": "English",
            "Hindi": "हिन्दी",
            "Marathi": "मराठी",
        }[option],
    )
    return language


def t(key: str, **values: object) -> str:
    language = st.session_state.get("selected_language", "English")
    translations = TRANSLATIONS.get(language, TRANSLATIONS["English"])
    text = translations.get(key, TRANSLATIONS["English"].get(key, key))
    return text.format(**values)


def ingredient_name(name: str) -> str:
    language = st.session_state.get("selected_language", "English")
    return INGREDIENT_TRANSLATIONS.get(language, {}).get(name, name)
